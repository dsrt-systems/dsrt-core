"""
C11.6 — Adaptive Execution Controller domain schemas.

Defines trigger classifications, allowed adaptation actions, execution events,
adaptation decisions, and audit records per spec §7.
"""

from __future__ import annotations

import enum
from typing import Any

from pydantic import BaseModel, Field


class AdaptationTriggerType(str, enum.Enum):
    """Execution situations that require adaptive intervention."""
    MODEL_OUTPUT_INVALID = "model_output_invalid"
    MODEL_REPEATED_FAILURE = "model_repeated_failure"
    TOOL_UNAVAILABLE = "tool_unavailable"
    TOOL_EXECUTION_ERROR = "tool_execution_error"
    TEST_FAILURE = "test_failure"
    RETRIEVAL_INSUFFICIENT = "retrieval_insufficient"
    CONTEXT_LIMIT_EXCEEDED = "context_limit_exceeded"
    VERIFICATION_FAILURE = "verification_failure"
    BUDGET_WARNING = "budget_warning"
    BUDGET_EXHAUSTED = "budget_exhausted"
    LATENCY_OVERRUN = "latency_overrun"
    REQUIREMENTS_UNRESOLVED = "requirements_unresolved"


class AdaptationActionType(str, enum.Enum):
    """Bounded recovery and adaptation actions."""
    RETRY_CONSTRAINED = "retry_constrained"
    TARGETED_RETRIEVAL = "targeted_retrieval"
    BOUNDED_REPAIR = "bounded_repair"
    TOOL_FALLBACK = "tool_fallback"
    RECOMPILE_CONTEXT = "recompile_context"
    MODEL_ESCALATION = "model_escalation"
    RECONCILE_PARALLEL = "reconcile_parallel"
    PARTIAL_REPAIR = "partial_repair"
    REDUCE_OPTIONAL_OPS = "reduce_optional_ops"
    RECOMMEND_FASTER_CONFIG = "recommend_faster_config"
    REQUEST_APPROVAL = "request_approval"
    STOP_EXECUTION = "stop_execution"


class ExecutionEvent(BaseModel):
    """
    Telemetry event received from C10 during execution monitoring.
    """
    event_id: str
    execution_id: str
    workspace_id: str = ""
    event_type: str
    step_id: str | None = None
    attempt_number: int = 1
    current_cost: float = Field(0.0, ge=0.0)
    current_latency_ms: int = Field(0, ge=0)
    error_message: str | None = None
    details: dict[str, Any] = Field(default_factory=dict)


class AdaptationDecision(BaseModel):
    """
    Recommended adaptation response generated by C11.6.
    Sent to C10 for validation and execution.
    """
    decision_id: str
    execution_id: str
    trigger_type: AdaptationTriggerType
    recommended_action: AdaptationActionType
    target_model_fingerprint: str | None = None
    target_tool: str | None = None
    max_attempts: int = 1
    current_attempt: int = 1
    estimated_adaptation_cost: float = Field(0.0, ge=0.0)
    reason: str
    requires_user_approval: bool = False
    is_bounded: bool = True
    metadata: dict[str, Any] = Field(default_factory=dict)


class AdaptationRecord(BaseModel):
    """Audit record tracking the lifecycle of an adaptation decision."""
    record_id: str
    execution_id: str
    decision: AdaptationDecision
    status: str = Field("proposed", description="proposed, approved, rejected, applied, failed")
    outcome_message: str | None = None
    applied_at_step: str | None = None